const LOCALES = { fr: 'fr-FR', nl: 'nl-BE', en: 'en-GB' };

export function mtLangKey(lang) {
  return STRINGS[lang] ? lang : 'fr';
}

export function mtLocale(lang) {
  return LOCALES[mtLangKey(lang)];
}

/** const t = useMtT(); t('years', { n: 20 }) → "20 ans" / "20 jaar" / "20 years". */
export function useMtT() {
  const lang = useMtLang();
  const t = (key, vars) => {
    const s = STRINGS[mtLangKey(lang.value)][key] ?? STRINGS.fr[key] ?? key;
    return vars ? s.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '') : s;
  };
  t.category = key => CATEGORIES[mtLangKey(lang.value)][key] || CATEGORIES.fr[key] || key;
  return t;
}
